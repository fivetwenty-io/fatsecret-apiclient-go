// TestRenderCompatibility_Structure verifies that RenderCompatibility produces
// valid matrix.go content with the expected structure.
func TestRenderCompatibility_Structure(t *testing.T) {
	root := repoRoot(t)
	specPath := filepath.Join(root, "spec", "fatsecret.yaml")

	spec, err := ir.ParseSpec(specPath)
	if err != nil {
		t.Fatalf("ir.ParseSpec: %v", err)
	}

	rf, err := RenderCompatibility(spec)
	if err != nil {
		t.Fatalf("RenderCompatibility: %v", err)
	}
	if rf.RelPath != "pkg/compatibility/matrix.go" {
		t.Errorf("RelPath = %q, want %q", rf.RelPath, "pkg/compatibility/matrix.go")
	}
	content := string(rf.Content)
	for _, want := range []string{
		"// Code generated by fsgen. DO NOT EDIT.",
		"package compatibility",
		"type Entry struct {",
		"var Matrix = []Entry{",
	} {
		if !strings.Contains(content, want) {
			t.Errorf("matrix.go missing expected fragment %q", want)
		}
	}
}

