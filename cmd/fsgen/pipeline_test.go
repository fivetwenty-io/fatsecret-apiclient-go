// TestPipeline_OverridesMissing verifies that Pipeline does not treat a
// missing overrides file as a file-read error; it proceeds (possibly failing
// later at the build step if the spec requires overrides to resolve duplicates,
// which is a spec-validity concern, not an overrides-file concern).
func TestPipeline_OverridesMissing(t *testing.T) {
	root := repoRoot(t)
	specPath := filepath.Join(root, "spec", "fatsecret.yaml")
	overridesPath := filepath.Join(root, "spec", "name_overrides.yaml")
	outDir := t.TempDir()

	// Use real overrides; confirm the happy path succeeds.
	if err := Pipeline(specPath, overridesPath, outDir, true); err != nil {
		t.Fatalf("Pipeline (dry-run): %v", err)
	}

	// Now verify that a non-existent overrides file is NOT treated as a read error.
	// The ir.ParseOverrides contract returns nil for os.IsNotExist.
	// We cannot use the real spec here (it requires overrides); use a minimal spec
	// that has no duplicates to confirm the nil-overrides path.
	dir := t.TempDir()
	minSpec := filepath.Join(dir, "min.yaml")
	minYAML := `version: "1"
types:
  R:
    kind: object
methods:
  - namespace: foods
    name: search
    version: 3
    http_verb: GET
    rest_path: /rest/foods/search/v3
    auth_tier: client_credentials
    response_type: R
`
	if err := os.WriteFile(minSpec, []byte(minYAML), 0o644); err != nil {
		t.Fatal(err)
	}
	missingOverrides := filepath.Join(t.TempDir(), "nonexistent_overrides.yaml")
	if err := Pipeline(minSpec, missingOverrides, t.TempDir(), false); err != nil {
		t.Fatalf("Pipeline with missing overrides file: %v", err)
	}
}

