// repoRoot returns the absolute path to the repository root by walking up from
// the test binary's working directory until go.mod is found.
func repoRoot(t *testing.T) string {
	t.Helper()
	dir, err := filepath.Abs(".")
	if err != nil {
		t.Fatalf("filepath.Abs: %v", err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("could not find repository root (go.mod not found)")
		}
		dir = parent
	}
}

// TestPipeline_Integration runs the full pipeline against the real spec and
// verifies the expected structural output.
func TestPipeline_Integration(t *testing.T) {
	root := repoRoot(t)
	specPath := filepath.Join(root, "spec", "fatsecret.yaml")
	overridesPath := filepath.Join(root, "spec", "name_overrides.yaml")
	outDir := t.TempDir()

	if err := Pipeline(specPath, overridesPath, outDir, false); err != nil {
		t.Fatalf("Pipeline: %v", err)
	}

	// Verify at least one namespace package directory was created under pkg/api/.
	apiDir := filepath.Join(outDir, "pkg", "api")
	entries, err := os.ReadDir(apiDir)
	if err != nil {
		t.Fatalf("expected pkg/api/ to exist: %v", err)
	}
	if len(entries) == 0 {
		t.Fatal("expected at least one namespace directory under pkg/api/")
	}

	// Find a service.go in any namespace dir and assert generated header.
	found := false
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		svcPath := filepath.Join(apiDir, e.Name(), "service.go")
		data, err := os.ReadFile(svcPath)
		if err != nil {
			continue
		}
		// Line 1 must be the generated header.
		firstLine := strings.SplitN(string(data), "\n", 2)[0]
		if firstLine != "// Code generated by fsgen. DO NOT EDIT." {
			t.Errorf("service.go in %q: line 1 = %q, want generated header", e.Name(), firstLine)
		}
		found = true
		break
	}
	if !found {
		t.Error("no service.go found under any namespace directory")
	}

	// Verify compatibility matrix was written.
	matrixPath := filepath.Join(outDir, "pkg", "compatibility", "matrix.go")
	matrixData, err := os.ReadFile(matrixPath)
	if err != nil {
		t.Fatalf("expected matrix.go to exist: %v", err)
	}
	if !strings.Contains(string(matrixData), "var Matrix = []Entry{") {
		t.Error("matrix.go missing expected Matrix variable declaration")
	}
}

// TestPipeline_Idempotent verifies that running the pipeline twice produces
// byte-identical output files.
func TestPipeline_Idempotent(t *testing.T) {
	root := repoRoot(t)
	specPath := filepath.Join(root, "spec", "fatsecret.yaml")
	overridesPath := filepath.Join(root, "spec", "name_overrides.yaml")

	out1 := t.TempDir()
	out2 := t.TempDir()

	if err := Pipeline(specPath, overridesPath, out1, false); err != nil {
		t.Fatalf("Pipeline run 1: %v", err)
	}
	if err := Pipeline(specPath, overridesPath, out2, false); err != nil {
		t.Fatalf("Pipeline run 2: %v", err)
	}

	// Walk out1 and compare every file against out2.
	err := filepath.Walk(out1, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(out1, path)
		b1, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		b2, err := os.ReadFile(filepath.Join(out2, rel))
		if err != nil {
			t.Errorf("file %q missing from second run: %v", rel, err)
			return nil
		}
		if !bytes.Equal(b1, b2) {
			t.Errorf("file %q differs between run 1 and run 2 (not idempotent)", rel)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("Walk error: %v", err)
	}
}

